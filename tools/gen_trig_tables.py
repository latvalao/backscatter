#!/usr/bin/env python3
"""Generates sim/core/trig_tables.gd — baked integer trig tables.

Tables are baked offline so the sim never evaluates float trig at runtime
(libm results can differ between platforms). Re-run only if resolution changes.
"""
import math, os

ONE = 65536          # fixed-point scale (16.16)
QUARTER = 1024       # sin table entries per quarter turn (+1 sentinel)
ATAN_N = 1024        # atan table entries for ratio 0..1 (+1 sentinel)
ANGLE_FULL = 65536   # binary angle units per turn

sin_q = [round(math.sin(i / QUARTER * math.pi / 2) * ONE) for i in range(QUARTER + 1)]
# atan(r) for r in [0,1], expressed in binary angle units (max = 8192 = 45 deg)
atan_t = [round(math.atan(i / ATAN_N) / (2 * math.pi) * ANGLE_FULL) for i in range(ATAN_N + 1)]

def fmt(name, arr):
    lines = []
    for i in range(0, len(arr), 16):
        lines.append("\t" + ", ".join(str(v) for v in arr[i:i + 16]) + ",")
    return f"const {name}: Array[int] = [\n" + "\n".join(lines) + "\n]\n"

out = os.path.join(os.path.dirname(__file__), "..", "sim", "core", "trig_tables.gd")
with open(out, "w") as f:
    f.write("# SIM: deterministic — no floats, no Nodes\n")
    f.write("# GENERATED by tools/gen_trig_tables.py — do not edit by hand.\n")
    f.write("class_name TrigTables\nextends RefCounted\n\n")
    f.write(f"const ONE: int = {ONE}\nconst QUARTER: int = {QUARTER}\nconst ATAN_N: int = {ATAN_N}\n\n")
    f.write("## sin(i/QUARTER * 90deg) * ONE, i in [0, QUARTER]\n")
    f.write(fmt("SIN_Q", sin_q) + "\n")
    f.write("## atan(i/ATAN_N) in binary angle units (65536 = full turn), i in [0, ATAN_N]\n")
    f.write(fmt("ATAN", atan_t))
print("wrote", os.path.normpath(out))
